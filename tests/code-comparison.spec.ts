import {test, expect} from '@playwright/test';
import {expectNoPageOverflow} from './layout-helpers';

test('reviewing edits is read-only, updates live, and follows the current chapter', async ({page}) => {
  let executions = 0;
  await page.route('**/python.worker.js', route => { executions++; return route.abort(); });
  await page.goto('/#/lesson/functions');
  await page.getByRole('tab', {name: '代码实现', exact: true}).click();
  const editor = page.getByRole('textbox', {name: 'Python 代码编辑器'});
  const starter = await editor.inputValue();
  const summary = page.getByText('查看我的改动（与初始代码比较）', {exact: true});
  await expect(page.getByRole('region', {name: '代码改动明细'})).toHaveCount(0);
  await summary.click();
  await expect(page.getByText('与初始代码相同。', {exact: true})).toBeVisible();
  const edited = `${starter}\nprint("<script id='diff-injection'>$x$</script>")`;
  await editor.fill(edited);
  const details = page.getByRole('region', {name: '代码改动明细'});
  await expect(details).toBeVisible();
  await expect(page.locator('[data-change="added"]')).toHaveCount(1);
  await expect(page.locator('[data-change="removed"]')).toHaveCount(0);
  await expect(details.locator('code').last()).toContainText("<script·id='diff-injection'>$x$</script>");
  await expect(page.locator('#diff-injection')).toHaveCount(0);
  await expect(details.locator('.katex')).toHaveCount(0);
  await expect(editor).toHaveValue(edited);
  await summary.click();
  await expect(details).toHaveCount(0);
  await summary.click();
  await expect(details).toBeVisible();
  await expect(editor).toHaveValue(edited);
  expect(executions).toBe(0);
  await page.getByRole('button', {name: '重置代码', exact: true}).click();
  await expect(page.getByText('与初始代码相同。', {exact: true})).toBeVisible();
  await expect(editor).toHaveValue(starter);
  await page.goto('/#/lesson/linear');
  await page.getByRole('tab', {name: '代码实现', exact: true}).click();
  await summary.click();
  await expect(page.getByText('与初始代码相同。', {exact: true})).toBeVisible();
});

test('keyboard disclosure and a narrow viewport keep long code contained', async ({page}) => {
  await page.setViewportSize({width: 390, height: 844});
  await page.goto('/#/lesson/functions');
  await page.getByRole('tab', {name: '代码实现', exact: true}).click();
  const editor = page.getByRole('textbox', {name: 'Python 代码编辑器'});
  await editor.fill(`    print('${'x'.repeat(500)}')`);
  const summary = page.getByText('查看我的改动（与初始代码比较）', {exact: true});
  await summary.focus();
  await page.keyboard.press('Enter');
  const details = page.getByRole('region', {name: '代码改动明细'});
  await expect(details).toBeVisible();
  await expect(details.locator('[data-change="added"] code')).toHaveText(`····print('${'x'.repeat(500)}')`);
  await expectNoPageOverflow(page);
  await page.keyboard.press('Tab');
  await expect(details).toBeFocused();
  expect(await details.evaluate(el => el.scrollWidth > el.clientWidth)).toBe(true);
  await editor.fill('x'.repeat(100_001));
  await expect(page.getByText('代码较长，暂不显示逐行比较；仍可继续编辑和运行。')).toBeVisible();
  await expect(details).toHaveCount(0);
  await expect(editor).toHaveValue('x'.repeat(100_001));
  await editor.fill('pass');
  await expect(details).toBeVisible();
});
